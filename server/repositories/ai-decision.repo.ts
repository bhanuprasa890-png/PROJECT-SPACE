export interface LineContextRow {
  id: string;
  agency_id: string;
  agency_name: string;
  timezone: string;
  code: string;
  name: string;
  color: string;
  mode: TransitMode;
  capacity_per_vehicle: number;
  headway_minutes: number;
  /** Sum of daily boardings across the route's stops — the reach estimate. */
  corridor_daily_boardings: number;
}

export async function getLineContext(
  db: Queryable,
  lineIdOrCode: string,
): Promise<LineContextRow | null> {
  return db.one<LineContextRow>(
    `select
       l.id,
       l.agency_id,
       a.name        as agency_name,
       a.timezone,
       l.code,
       l.name,
       l.color,
       l.mode,
       l.capacity_per_vehicle,
       l.headway_minutes,
       (select coalesce(sum(s.daily_boardings), 0)::int
          from line_stops ls join stops s on s.id = ls.stop_id
         where ls.line_id = l.id) as corridor_daily_boardings
     from lines l
     join agencies a on a.id = l.agency_id
     where l.id = $1 or l.code = $1
     limit 1`,
    [lineIdOrCode],
  );
}

