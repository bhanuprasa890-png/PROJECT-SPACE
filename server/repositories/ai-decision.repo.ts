const SELECT_INTERVENTION = `select * from v_ai_interventions`;

export async function listInterventions(
  db: Queryable,
  limit = 8,
): Promise<InterventionReadRow[]> {
  return db.query<InterventionReadRow>(
    `${SELECT_INTERVENTION}
      where status = 'applied'
      order by applied_at desc nulls last, detected_at desc
      limit $1`,
    [limit],
  );
}

/** Latest applied intervention per route — drives the "AI applied" route badge. */
export async function listInterventionsByLine(
  db: Queryable,
  windowHours = 24,
): Promise<InterventionReadRow[]> {
  return db.query<InterventionReadRow>(
    `select distinct on (line_id) *
       from v_ai_interventions
      where status = 'applied'
        and applied_at >= now() - make_interval(hours => $1)
      order by line_id, applied_at desc`,
    [windowHours],
  );
}

export async function countInterventionsSince(
  db: Queryable,
  windowHours = 24,
): Promise<number> {
  const row = await db.one<{ count: string }>(
    `select count(*)::text as count
       from ai_decisions
      where status = 'applied'
        and applied_at >= now() - make_interval(hours => $1)`,
    [windowHours],
  );
  return Number(row?.count ?? 0);
}

export async function getIntervention(
  db: Queryable,
  id: string,
): Promise<InterventionReadRow | null> {
  return db.one<InterventionReadRow>(`${SELECT_INTERVENTION} where id = $1`, [id]);
}

/** Applied interventions that must not be applied twice within the cooldown. */
export async function findRecentIntervention(
  db: Queryable,
  lineId: string,
  cooldownMinutes = 10,
): Promise<InterventionReadRow | null> {
  return db.one<InterventionReadRow>(
    `${SELECT_INTERVENTION}
      where line_id = $1 and status = 'applied'
        and applied_at >= now() - make_interval(mins => $2)
      order by applied_at desc
      limit 1`,
    [lineId, cooldownMinutes],
  );
}

